assert(builder:find('textureRoot="cache/stages/relic_chamber/source"',1,true),"Relic Chamber source textures are not isolated")
assert(builder:find('g.texture={path=path,w=t.w,h=t.h,wrapS=t.wrapS,wrapT=t.wrapT,',1,true),"source GX wrap contract regressed")
assert(builder:find('coordinateMode=t.coordinateMode,colorMap=t.colorMap,alphaMap=t.alphaMap,blending=t.blending',1,true),"source texture coordinate/color state was discarded")
assert(native:find('"M3_shrine_1F_bf.fsys"',1,true),"native raw/CISO validation does not require shrine source")
