local function read(path)
  local f=assert(io.open(path,"rb"));local s=f:read("*a");f:close();return s
end

local catalog=read("lib/ArenaCatalog.lua")
local builder=read("extract/ArenaBuilder.lua")
local pipeline=read("extract/BuildPipeline.lua")
local cache=read("lib/CacheManager.lua")
local native=read("lib/NativeLauncherCompat.lua")
local arena=read("lib/Arena.lua")
local settings=read("lib/BattleSettings.lua")

assert(catalog:find('id="relic_chamber",label="RELIC CHAMBER"',1,true),"Relic Chamber missing from arena catalog")
assert(catalog:find('{id="relic_chamber",label="RELIC CHAMBER"}',1,true),"Relic Chamber missing from arena selector options")
assert(settings:find('relic_chamber=true',1,true),"Relic Chamber rejected by battle settings")
assert(builder:find('sourceFsys="M3_shrine_1F_bf.fsys"',1,true),"Agate shrine battle FSYS is not source-backed")
