-- Critical migration rule: adding one arena must not invalidate extractor/audio.
assert(pipeline:find('local B={cacheVersion=2,extractorRevision=15}',1,true),"Relic arena update unexpectedly invalidates global extraction cache")
assert(pipeline:find('arenasOnly=function',1,true),"arena-only migration path missing")
