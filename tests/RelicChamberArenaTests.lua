assert(catalog:find('maxRadius=36',1,true) and catalog:find('maxY=13.5',1,true),"Relic Chamber source-shell camera volume missing")
assert(not catalog:find('cameraOccluderTrim=true',1,true),"legacy centre-ray Relic trim should stay disabled")
