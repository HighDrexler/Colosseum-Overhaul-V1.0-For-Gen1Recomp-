local function num(v) v=tonumber(v);if v and v==v and v>-math.huge and v<math.huge then return v end end



local function stemMatches(dex,stem,Dex)
if stem==nil then return false end
stem=tostring(stem):gsub("^rare_","")
local row=Dex and Dex.species and Dex.species[dex]
if type(row)~="table" or row[1]==nil then return false end
return tostring(row[1])==stem
end





function S.sourcePerCache(scene,dex,Dex)
if type(scene)~="table" then return nil,"no-scene" end
local norm=type(scene.sourceNormalization)=="table" and scene.sourceNormalization or nil
local s=norm and num(norm.s)
if s and s>0 then return 1/s,"cache-source-normalization",norm end
local rb=type(scene.retailWazaOwnerBound)=="table" and scene.retailWazaOwnerBound or nil
local affine=rb and rb.exact==true and type(rb.sourceToCache)=="table" and rb.sourceToCache or nil
s=affine and num(affine.s)
if s and s>0 then return 1/s,"retail-owner-bound-affine",affine end
dex=num(dex) or num(scene.dex)
local h=dex and S.SOURCE_HEIGHT[dex]
if not h then return nil,"no-source-height" end
if not stemMatches(dex,scene.stem,Dex) then return nil,"stem-mismatch" end
local b=scene.bounds
local ch=b and b.min and b.max and ((num(b.max[2]) or 0)-(num(b.min[2]) or 0)) or nil
if not (ch and math.abs(ch-S.CACHE_HEIGHT)<.05) then return nil,"cache-height-unexpected" end
return h/S.CACHE_HEIGHT,"gc6e01-measured-table",nil
end








function S.policy(scene,dex,Dex)
local perCache,provenance,affine=S.sourcePerCache(scene,dex,Dex)
if not perCache then return nil,provenance end
local b=scene.bounds
local ch=b and b.min and b.max and ((num(b.max[2]) or 0)-(num(b.min[2]) or 0)) or S.CACHE_HEIGHT
ch=math.max(.001,ch)
local sourceHeight=ch*perCache
local hover=0
local cy=affine and num(affine.cy)
if cy and cy>0 then hover=cy/perCache end
return {
relative=sourceHeight/S.HUMAN_SOURCE_HEIGHT,sourceHeight=sourceHeight,
sourcePerCache=perCache,unitsPerSource=S.UNITS_PER_SOURCE,
worldHeight=sourceHeight*S.UNITS_PER_SOURCE,
hoverCache=hover,hoverSource=(cy and cy>0) and cy or 0,
provenance=provenance,exact=provenance~="gc6e01-measured-table",
coreCorrection=1,stance=1,body=1,
}
end

S._test={stemMatches=stemMatches}
return S
